#ifndef VIMAR_ZB_DIMMABLE_LIGHT_H
#define VIMAR_ZB_DIMMABLE_LIGHT_H

#define ZB_DIMMABLE_LIGHT_DEVICE_ID 0x0101
#define ZB_DEVICE_VER_DIMMABLE_LIGHT 1
#define ZB_DIMMABLE_LIGHT_IN_CLUSTER_NUM 7
#if defined(CONFIG_VIMAR_ZIGBEE_OTA)
#define ZB_DIMMABLE_LIGHT_OUT_CLUSTER_NUM 1
#define VIMAR_OTA_CLUSTER_DESC ZB_ZCL_CLUSTER_DESC(ZB_ZCL_CLUSTER_ID_OTA_UPGRADE, VIMAR_OTA_ATTR_COUNT, vimar_ota_attrs, ZB_ZCL_CLUSTER_CLIENT_ROLE, ZB_ZCL_MANUF_CODE_INVALID),
#define VIMAR_OTA_CLUSTER_ID , ZB_ZCL_CLUSTER_ID_OTA_UPGRADE
#else
#define ZB_DIMMABLE_LIGHT_OUT_CLUSTER_NUM 0
#define VIMAR_OTA_CLUSTER_DESC
#define VIMAR_OTA_CLUSTER_ID
#endif
#define ZB_DIMMABLE_LIGHT_REPORT_ATTR_COUNT \
    (ZB_ZCL_ON_OFF_REPORT_ATTR_COUNT + ZB_ZCL_LEVEL_CONTROL_REPORT_ATTR_COUNT)
#define ZB_DIMMABLE_LIGHT_CVC_ATTR_COUNT 1

#define ZB_DECLARE_DIMMABLE_LIGHT_CLUSTER_LIST(name, basic, identify, groups, scenes, onoff, level, custom) \
    zb_zcl_cluster_desc_t name[] = { \
        VIMAR_OTA_CLUSTER_DESC \
        ZB_ZCL_CLUSTER_DESC(ZB_ZCL_CLUSTER_ID_IDENTIFY, ZB_ZCL_ARRAY_SIZE(identify, zb_zcl_attr_t), identify, ZB_ZCL_CLUSTER_SERVER_ROLE, ZB_ZCL_MANUF_CODE_INVALID), \
        ZB_ZCL_CLUSTER_DESC(ZB_ZCL_CLUSTER_ID_BASIC, ZB_ZCL_ARRAY_SIZE(basic, zb_zcl_attr_t), basic, ZB_ZCL_CLUSTER_SERVER_ROLE, ZB_ZCL_MANUF_CODE_INVALID), \
        ZB_ZCL_CLUSTER_DESC(ZB_ZCL_CLUSTER_ID_SCENES, ZB_ZCL_ARRAY_SIZE(scenes, zb_zcl_attr_t), scenes, ZB_ZCL_CLUSTER_SERVER_ROLE, ZB_ZCL_MANUF_CODE_INVALID), \
        ZB_ZCL_CLUSTER_DESC(ZB_ZCL_CLUSTER_ID_GROUPS, ZB_ZCL_ARRAY_SIZE(groups, zb_zcl_attr_t), groups, ZB_ZCL_CLUSTER_SERVER_ROLE, ZB_ZCL_MANUF_CODE_INVALID), \
        ZB_ZCL_CLUSTER_DESC(ZB_ZCL_CLUSTER_ID_ON_OFF, ZB_ZCL_ARRAY_SIZE(onoff, zb_zcl_attr_t), onoff, ZB_ZCL_CLUSTER_SERVER_ROLE, ZB_ZCL_MANUF_CODE_INVALID), \
        ZB_ZCL_CLUSTER_DESC(ZB_ZCL_CLUSTER_ID_LEVEL_CONTROL, ZB_ZCL_ARRAY_SIZE(level, zb_zcl_attr_t), level, ZB_ZCL_CLUSTER_SERVER_ROLE, ZB_ZCL_MANUF_CODE_INVALID), \
        ZB_ZCL_CLUSTER_DESC(VIMAR_CUSTOM_CLUSTER_ID, ZB_ZCL_ARRAY_SIZE(custom, zb_zcl_attr_t), custom, ZB_ZCL_CLUSTER_SERVER_ROLE, ZB_ZCL_MANUF_CODE_INVALID), \
    }

#define ZB_DECLARE_DIMMABLE_LIGHT_SIMPLE_DESC(name, endpoint, in_count, out_count) \
    ZB_DECLARE_SIMPLE_DESC(in_count, out_count); \
    ZB_AF_SIMPLE_DESC_TYPE(in_count, out_count) simple_desc_##name = { \
        endpoint, ZB_AF_HA_PROFILE_ID, ZB_DIMMABLE_LIGHT_DEVICE_ID, ZB_DEVICE_VER_DIMMABLE_LIGHT, 0, \
        in_count, out_count, { \
            ZB_ZCL_CLUSTER_ID_BASIC, ZB_ZCL_CLUSTER_ID_IDENTIFY, ZB_ZCL_CLUSTER_ID_SCENES, \
            ZB_ZCL_CLUSTER_ID_GROUPS, ZB_ZCL_CLUSTER_ID_ON_OFF, ZB_ZCL_CLUSTER_ID_LEVEL_CONTROL, VIMAR_CUSTOM_CLUSTER_ID VIMAR_OTA_CLUSTER_ID } }

#define ZB_DECLARE_DIMMABLE_LIGHT_EP(name, endpoint, clusters) \
    ZB_DECLARE_DIMMABLE_LIGHT_SIMPLE_DESC(name, endpoint, \
        ZB_DIMMABLE_LIGHT_IN_CLUSTER_NUM, ZB_DIMMABLE_LIGHT_OUT_CLUSTER_NUM); \
    ZBOSS_DEVICE_DECLARE_REPORTING_CTX(reporting_##name, ZB_DIMMABLE_LIGHT_REPORT_ATTR_COUNT); \
    ZBOSS_DEVICE_DECLARE_LEVEL_CONTROL_CTX(cvc_##name, ZB_DIMMABLE_LIGHT_CVC_ATTR_COUNT); \
    ZB_AF_DECLARE_ENDPOINT_DESC(name, endpoint, ZB_AF_HA_PROFILE_ID, 0, NULL, \
        ZB_ZCL_ARRAY_SIZE(clusters, zb_zcl_cluster_desc_t), clusters, \
        (zb_af_simple_desc_1_1_t *)&simple_desc_##name, \
        ZB_DIMMABLE_LIGHT_REPORT_ATTR_COUNT, reporting_##name, \
        ZB_DIMMABLE_LIGHT_CVC_ATTR_COUNT, cvc_##name)

#endif
